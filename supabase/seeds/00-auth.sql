-- LOCAL DEVELOPMENT ONLY. Auth is available at native startup, before app migrations.
-- Existing local users keep their UUID/password; never delete accounts or sessions.
INSERT INTO auth.users (
    instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change
)
SELECT
    '00000000-0000-0000-0000-000000000000', gen_random_uuid(),
    'authenticated', 'authenticated', 'owner@local.test',
    extensions.crypt('local-dev-password', extensions.gen_salt('bf')),
    now(), '{"provider":"email","providers":["email"]}'::jsonb,
    '{"name":"Local Owner"}'::jsonb, now(), now(), '', '', '', ''
WHERE NOT EXISTS (SELECT FROM auth.users WHERE lower(email) = 'owner@local.test');

-- Auth identities are required for email/password sign-in; email is generated by Auth.
INSERT INTO auth.identities (
    id, user_id, provider_id, identity_data, provider, created_at, updated_at
)
SELECT gen_random_uuid(), id, id::text,
    jsonb_build_object('sub', id::text, 'email', email, 'email_verified', true),
    'email', now(), now()
FROM auth.users WHERE lower(email) = 'owner@local.test'
ON CONFLICT (provider_id, provider) DO NOTHING;
